def planner_user(topic: str, n: int) -> str:
    return f"موضوع: {topic}\nتعداد زیرسؤال: {n}"


def extractor_user(question: str, title: str, url: str, text: str) -> str:
    return (
        f"زیرسؤال: {question}\n"
        f"عنوان صفحه: {title}\n"
        f"آدرس: {url}\n"
        f"--- متن صفحه ---\n{text}\n--- پایان متن ---"
    )


def verifier_user(claim: str, evidence: str) -> str:
    return f"ادعا: {claim}\nشاهد: {evidence}"


def writer_user(topic: str, blocks: list[tuple[str, list[str]]], partial: bool) -> str:
    """blocks: list of (sub-question, [formatted finding lines])."""
    parts = [f"موضوع پژوهش: {topic}"]
    if partial:
        parts.append("توجه: پژوهش ناتمام ماند؛ گزارش را در بخش محدودیت‌ها «جزئی» اعلام کن.")
    for question, lines in blocks:
        parts.append(f"\nزیرسؤال: {question}")
        parts.extend(lines)
    return "\n".join(parts)
